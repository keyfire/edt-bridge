package io.github.keyfire.edtbridge.edt;

import java.util.IdentityHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;

import org.eclipse.emf.common.util.Enumerator;
import org.eclipse.emf.ecore.EAttribute;
import org.eclipse.emf.ecore.EObject;
import org.eclipse.emf.ecore.EReference;
import org.eclipse.emf.ecore.EStructuralFeature;
import com._1c.g5.v8.dt.form.layout.model.platform.border.V8Border;
import com._1c.g5.v8.dt.form.layout.model.platform.color.Color;
import com._1c.g5.v8.dt.form.layout.model.platform.color.ColorKind;
import com._1c.g5.v8.dt.form.layout.model.platform.font.Font;
import com._1c.g5.v8.dt.form.layout.model.platform.font.FontKind;
import com._1c.g5.v8.dt.form.layout.model.platform.picture.PictureKind;
import com._1c.g5.v8.dt.form.layout.model.platform.picture.V8Picture;
import com._1c.g5.v8.dt.form.model.AbstractDataPath;
import com._1c.g5.v8.dt.form.model.Button;
import com._1c.g5.v8.dt.form.model.DataItem;
import com._1c.g5.v8.dt.form.model.FormStandardCommand;
import com._1c.g5.v8.dt.form.model.Titled;
import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonNull;
import com.google.gson.JsonObject;
import com.google.gson.JsonPrimitive;

/**
 * The client view model of a form: EDT's laid-out form description (HippoLayForm, the input the form
 * editor preview draws from) as JSON, with the values a drawing needs made plain (colors as #rrggbb,
 * pictures by name, fonts by weight and height), each command button told apart by the command behind
 * it, and the texts EDT takes from its own locale given in the language of the configuration.
 *
 * <p>The tree keeps EDT's class names ({@code HippoLayEdit}, {@code HippoLayTumbler}, ...) and feature
 * names: the drawing in the edt-bridge-mcp wrapper reads them. The node count is capped so a large
 * form cannot flood the answer.
 */
final class FormClientView {

    /** Features with no bearing on the drawing: back links, internal flags, look of states. */
    private static final Set<String> SKIP = Set.of("pParent", "categoriesHolder", "multipleValuesFont",
            "textColorHover", "textColorPressed", "hoverPicture", "pressedPicture", "useStdFontForWidthCalculate",
            "useStdFontForMaxWidthCalculate");

    private final String language;
    private final boolean v85;
    private final EdtTexts texts;
    private final int maxNodes;
    private int nodes;
    private boolean truncated;
    private final Map<EObject, Integer> seen = new IdentityHashMap<>();
    /**
     * Titles of the form items as written, by item name and language, read before EDT laid the form
     * out: the layout fills the titles it draws with its defaults, in its own locale. Null when the
     * written form is not known; an item missing from it was generated by EDT (an auto-filled button).
     */
    private final Map<String, Map<String, String>> written;
    /** Synonyms the configuration gives standard attributes of the form's object (Code shown as "ID"). */
    private Map<String, String> standardTitles = Map.of();

    FormClientView(String language, boolean v85, int maxNodes, Map<String, Map<String, String>> written) {
        this.language = language == null || language.isBlank() ? "ru" : language;
        this.v85 = v85;
        this.texts = EdtTexts.forLanguage(this.language);
        this.maxNodes = maxNodes;
        this.written = written;
    }

    /** Synonyms of the owner object's standard attributes in the configuration language, by name. */
    FormClientView standardTitles(EObject owner) {
        Map<String, String> found = new java.util.HashMap<>();
        if (owner != null) {
            EStructuralFeature f = owner.eClass().getEStructuralFeature("standardAttributes");
            Object list = f == null ? null : owner.eGet(f);
            if (list instanceof List) {
                for (Object a : (List<?>) list) {
                    if (a instanceof EObject) {
                        String name = stringFeature((EObject) a, "name");
                        String synonym = mapFeature((EObject) a, "synonym");
                        if (name != null && synonym != null) {
                            found.put(name, synonym);
                        }
                    }
                }
            }
        }
        standardTitles = found;
        return this;
    }

    boolean truncated() {
        return truncated;
    }

    /** The view of a laid-out form element (the root is the HippoLayForm). */
    JsonElement view(EObject o) {
        if (o == null) {
            return JsonNull.INSTANCE;
        }
        Integer id = seen.get(o);
        if (id != null) {
            JsonObject ref = new JsonObject();
            ref.addProperty("_seen", id);
            return ref;
        }
        if (nodes >= maxNodes) {
            truncated = true;
            JsonObject cut = new JsonObject();
            cut.addProperty("_cut", o.eClass().getName());
            return cut;
        }
        int my = ++nodes;
        seen.put(o, my);
        JsonObject j = new JsonObject();
        j.addProperty("_c", o.eClass().getName());
        j.addProperty("_id", my);
        EObject modelElement = null;
        for (EStructuralFeature f : o.eClass().getEAllStructuralFeatures()) {
            if (SKIP.contains(f.getName())) {
                continue;
            }
            Object v;
            try {
                if (f.isDerived() && !(f instanceof EAttribute)) {
                    continue;
                }
                if (!o.eIsSet(f)) {
                    continue;
                }
                v = o.eGet(f);
            } catch (RuntimeException e) {
                continue;
            }
            if (f instanceof EAttribute) {
                JsonElement a = value(v);
                if (a != null) {
                    j.add(f.getName(), a);
                }
            } else if (f instanceof EReference) {
                EReference r = (EReference) f;
                if (r.isContainment()) {
                    if (v instanceof List) {
                        JsonArray arr = new JsonArray();
                        for (Object x : (List<?>) v) {
                            if (x instanceof EObject) {
                                arr.add(view((EObject) x));
                            }
                        }
                        j.add(f.getName(), arr);
                    } else if (v instanceof EObject) {
                        j.add(f.getName(), view((EObject) v));
                    }
                } else if ("formModelElement".equals(f.getName()) && v instanceof EObject) {
                    modelElement = (EObject) v;
                    j.add("formModelElement", modelElementOf(modelElement));
                } else if (v instanceof EObject) {
                    j.add(f.getName(), refOf((EObject) v));
                }
            }
        }
        localizeTitle(j, modelElement);
        return j;
    }

    /** A plain dump of a mapping model (the form's command interface), same value rules, no titles. */
    JsonElement plain(EObject o) {
        return view(o);
    }

    /** As {@link #FormClientView(String, boolean, int, Map)} with no written form. */
    FormClientView(String language, boolean v85, int maxNodes) {
        this(language, v85, maxNodes, null);
    }

    /**
     * What a laid-out element was built from: the form item (its own title, its data path), and for a
     * button its command.
     */
    private JsonObject modelElementOf(EObject e) {
        JsonObject r = refOf(e);
        String name = stringFeature(e, "name");
        if (written != null && name != null) {
            Map<String, String> titles = written.get(name);
            if (titles == null) {
                r.addProperty("generated", true);
            } else {
                String own = titles.get(language);
                if (own != null && !own.isBlank()) {
                    r.addProperty("title", own);
                }
            }
        }
        if (e instanceof DataItem) {
            String path = pathOf(((DataItem) e).getDataPath());
            if (path != null) {
                r.addProperty("dataPath", path);
            }
        }
        if (e instanceof Button) {
            Object command;
            try {
                command = ((Button) e).getCommandName();
            } catch (RuntimeException ex) {
                command = null;
            }
            if (command instanceof EObject) {
                EObject c = (EObject) command;
                JsonObject cmd = new JsonObject();
                if (c instanceof FormStandardCommand) {
                    cmd.addProperty("source", "standard");
                    cmd.addProperty("name", ((FormStandardCommand) c).getName());
                } else {
                    cmd.addProperty("source", c.eClass().getName());
                    String commandName = stringFeature(c, "name");
                    if (commandName != null) {
                        cmd.addProperty("name", commandName);
                    }
                    String title = mapFeature(c, "title");
                    if (title == null) {
                        title = mapFeature(c, "synonym");
                    }
                    if (title != null) {
                        cmd.addProperty("title", title);
                    }
                }
                r.add("command", cmd);
            }
        }
        return r;
    }

    /**
     * The title EDT wrote from its own locale, in the language of the configuration. Titles the
     * configuration gives (an item's own title, a synonym, a command title) are already there; what
     * is left is the platform's: standard attributes, standard commands, the line number column.
     */
    private void localizeTitle(JsonObject j, EObject modelElement) {
        if (!j.has("title") || !j.get("title").isJsonPrimitive()) {
            return;
        }
        String title = j.get("title").getAsString();
        String cls = j.get("_c").getAsString();
        JsonObject me = j.has("formModelElement") && j.get("formModelElement").isJsonObject()
                ? j.getAsJsonObject("formModelElement") : null;
        if ("HippoLayCommand".equals(cls) && me != null) {
            if (me.has("title")) {
                set(j, title, me.get("title").getAsString());
                return;
            }
            JsonObject cmd = me.has("command") ? me.getAsJsonObject("command") : null;
            if (cmd != null && cmd.has("title")) {
                set(j, title, cmd.get("title").getAsString());
                return;
            }
            if (cmd != null && "standard".equals(cmd.get("source").getAsString()) && texts != null) {
                String hint = cmd.has("name") ? cmd.get("name").getAsString() : null;
                set(j, title, texts.translate(title, hint, "FormStandardCommandFactory_"));
                return;
            }
        }
        if (texts == null || !isAscii(title) || (me != null && me.has("title"))) {
            return;
        }
        if ("HippoLaySubMenu".equals(cls)) {
            // Submenus EDT builds from command groups: "Create based on", "View mode".
            set(j, title, texts.translate(title, null, "FormCommandInterfaceMapping_", "IDS_"));
            return;
        }
        String hint = null;
        if (me != null && me.has("dataPath")) {
            String path = me.get("dataPath").getAsString();
            hint = path.substring(path.lastIndexOf('.') + 1);
            if (path.indexOf('.') == path.lastIndexOf('.') && standardTitles.containsKey(hint)) {
                set(j, title, standardTitles.get(hint));
                return;
            }
        }
        set(j, title, texts.translate(title, hint, "StandardAttribute_", "PropertyInfoDescription_",
                "FormStandardCommandFactory_"));
    }

    private static void set(JsonObject j, String was, String now) {
        if (now != null && !now.isBlank() && !now.equals(was)) {
            j.addProperty("title", now);
            j.addProperty("titleEdt", was);
        }
    }

    private JsonObject refOf(EObject x) {
        Integer id = seen.get(x);
        JsonObject r = new JsonObject();
        r.addProperty("_ref", x.eClass().getName());
        if (id != null) {
            r.addProperty("_id", id);
        }
        String name = stringFeature(x, "name");
        if (name != null) {
            r.addProperty("name", name);
        }
        return r;
    }

    private static String stringFeature(EObject x, String feature) {
        EStructuralFeature f = x.eClass().getEStructuralFeature(feature);
        if (f == null) {
            return null;
        }
        try {
            Object n = x.eGet(f);
            return n == null ? null : String.valueOf(n);
        } catch (RuntimeException e) {
            return null;
        }
    }

    private String mapFeature(EObject x, String feature) {
        EStructuralFeature f = x.eClass().getEStructuralFeature(feature);
        if (f == null) {
            return null;
        }
        try {
            Object v = x.eGet(f);
            if (v instanceof org.eclipse.emf.common.util.EMap) {
                v = ((org.eclipse.emf.common.util.EMap<?, ?>) v).map();
            }
            if (v instanceof Map) {
                Object s = ((Map<?, ?>) v).get(language);
                return s == null || String.valueOf(s).isBlank() ? null : String.valueOf(s);
            }
        } catch (RuntimeException e) {
            // a text that cannot be read is left out
        }
        return null;
    }

    private static String pathOf(AbstractDataPath dp) {
        if (dp == null) {
            return null;
        }
        try {
            List<String> segs = dp.getSegments();
            return segs == null || segs.isEmpty() ? null : String.join(".", segs);
        } catch (RuntimeException e) {
            return null;
        }
    }

    private static boolean isAscii(String s) {
        for (int i = 0; i < s.length(); i++) {
            if (s.charAt(i) > 127) {
                return false;
            }
        }
        return !s.isBlank();
    }

    private JsonElement value(Object v) {
        if (v == null) {
            return null;
        }
        if (v instanceof Boolean) {
            return new JsonPrimitive((Boolean) v);
        }
        if (v instanceof Number) {
            return new JsonPrimitive((Number) v);
        }
        if (v instanceof String) {
            return new JsonPrimitive((String) v);
        }
        if (v instanceof Enumerator) {
            return new JsonPrimitive(((Enumerator) v).getLiteral());
        }
        if (v instanceof Color) {
            return color((Color) v);
        }
        if (v instanceof V8Picture) {
            return picture((V8Picture) v);
        }
        if (v instanceof Font) {
            return font((Font) v);
        }
        if (v instanceof V8Border) {
            return null;
        }
        if (v instanceof org.eclipse.emf.common.util.EMap) {
            v = ((org.eclipse.emf.common.util.EMap<?, ?>) v).map();
        }
        if (v instanceof Map) {
            JsonObject m = new JsonObject();
            for (Map.Entry<?, ?> e : ((Map<?, ?>) v).entrySet()) {
                m.addProperty(String.valueOf(e.getKey()), String.valueOf(e.getValue()));
            }
            return m;
        }
        if (v instanceof List) {
            JsonArray arr = new JsonArray();
            for (Object x : (List<?>) v) {
                JsonElement e = value(x);
                arr.add(e == null ? JsonNull.INSTANCE : e);
            }
            return arr;
        }
        if (v instanceof EObject) {
            return view((EObject) v);
        }
        return null;
    }

    private static JsonElement color(Color c) {
        if (c.kind == null || c.kind == ColorKind.eAutoColor || c.isEmptyColor()) {
            return null;
        }
        if (c.kind == ColorKind.eV8Color) {
            return new JsonPrimitive("style:" + c.getCompositeId());
        }
        return new JsonPrimitive(String.format("#%02x%02x%02x", c.getRed(), c.getGreen(), c.getBlue()));
    }

    private static JsonElement picture(V8Picture p) {
        try {
            if (p.getKind() == null || p.getKind() == PictureKind.eNonePicture) {
                return null;
            }
            String raw = p.getRawImageName();
            if (raw != null && !raw.isBlank()) {
                return new JsonPrimitive(raw);
            }
            EObject mp = p.getPicture();
            if (mp != null) {
                String name = stringFeature(mp, "name");
                return new JsonPrimitive(mp.eClass().getName() + (name == null ? "" : ":" + name));
            }
        } catch (RuntimeException e) {
            // a picture that cannot be named is left out
        }
        return null;
    }

    private static JsonElement font(Font f) {
        if (f.kind == null || f.kind == FontKind.eAutoFont) {
            return null;
        }
        JsonObject o = new JsonObject();
        o.addProperty("kind", f.kind.name());
        if (f.logFont != null) {
            if (f.logFont.lfHeight != 0) {
                o.addProperty("height", f.logFont.lfHeight);
            }
            if (f.logFont.lfWeight >= 600) {
                o.addProperty("bold", true);
            }
            if (f.logFont.lfItalic) {
                o.addProperty("italic", true);
            }
            if (f.logFont.lfUnderline) {
                o.addProperty("underline", true);
            }
            if (f.logFont.lfFaceName != null && !f.logFont.lfFaceName.isBlank()) {
                o.addProperty("face", f.logFont.lfFaceName);
            }
        }
        if (f.scale != 0 && f.scale != 100) {
            o.addProperty("scale", f.scale);
        }
        if (f.ref != null) {
            o.addProperty("style", f.ref.toString());
        }
        return o;
    }
}
